"""Finds the slow functions of fake user generation: stored procedure steps and Python functions.

python src/bottlenecks.py --users 100000 --locales en_US de_DE --workers 6
"""
import argparse
import sys
from dataclasses import replace
from pathlib import Path
from urllib.parse import urlparse

from dotenv import load_dotenv

sys.path.insert(0, str(Path(__file__).resolve().parent))
from benchmark import DEFAULT_CHUNK, DEFAULT_WORKERS, LOCAL_HOSTS, print_progress, server_label
from fakerdb.benchmark import BenchmarkPlan
from fakerdb.config import ROOT, Settings
from fakerdb.database import Database
from fakerdb.profiler import (TOTAL_STEP, FunctionCost, PrimitiveCost, StepCost, layer_seconds, profile_primitives,
                              profile_python, profile_steps, top_functions)
from fakerdb.repository import StoredProcedureFaker

DEFAULT_USERS = 10_000
DEFAULT_SQL_USERS = 5_000
DEFAULT_PRIMITIVE_CALLS = 500
DEFAULT_TOP = 15

def parse_args(settings: Settings) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--users", type=int, default=DEFAULT_USERS,
                        help="users fetched end to end through StoredProcedureFaker.users under cProfile, "
                             "one worker process per connection (0 = skip)")
    parser.add_argument("--sql-users", type=int, default=DEFAULT_SQL_USERS,
                        help="users generated by faker_profile_users to time each step in the database (0 = skip)")
    parser.add_argument("--primitive-calls", type=int, default=DEFAULT_PRIMITIVE_CALLS,
                        help="calls of each building block in faker_profile_primitives (0 = skip)")
    parser.add_argument("--locales", nargs="+", help="locale codes (default: every locale in the database)")
    parser.add_argument("--workers", type=int, default=DEFAULT_WORKERS, help="parallel connections")
    parser.add_argument("--chunk", type=int, default=DEFAULT_CHUNK, help="users per procedure call")
    parser.add_argument("--seed", type=int, default=settings.default_seed)
    parser.add_argument("--about-sentences", type=int, default=settings.about_sentences)
    parser.add_argument("--top", type=int, default=DEFAULT_TOP, help="Python functions to list")
    parser.add_argument("--allow-remote", action="store_true", help="allow a non-local DATABASE_URL")
    args = parser.parse_args()
    if args.users % args.chunk:
        parser.error("--users must be a multiple of --chunk (users are fetched in whole batches)")
    return args

def print_steps(steps: list[StepCost]) -> None:
    total = next(s for s in steps if s.step == TOTAL_STEP)
    users = total.calls
    print(f"\nDatabase, one user step by step ({users:,} users, summed over connections: {total.seconds:,.1f} s)\n")
    print("| Step | ms per user | Share |")
    print("|------|------------:|------:|")
    for s in sorted((s for s in steps if s is not total), key=lambda s: s.seconds, reverse=True):
        print(f"| {s.step} | {s.us_per_call / 1000:.2f} | {s.seconds / total.seconds:.1%} |")
    print(f"| **{TOTAL_STEP}** | **{total.us_per_call / 1000:.2f}** | 100% |")

def print_primitives(primitives: list[PrimitiveCost]) -> None:
    print(f"\nDatabase, one call of each building block ({primitives[0].calls:,} calls each)\n")
    print("| Building block | us per call | us over empty loop |")
    print("|----------------|------------:|-------------------:|")
    for p in sorted(primitives, key=lambda p: p.us_per_call, reverse=True):
        print(f"| {p.primitive} | {p.us_per_call:,.1f} | {p.us_over_loop:,.1f} |")

def print_python(users: int, wall: float, layers: dict[str, float], functions: list[FunctionCost]) -> None:
    worker_seconds = sum(layers.values())
    print(f"\nPython, end to end ({users:,} users in {wall:,.1f} s = {users / wall:,.0f} users/s; "
          f"{worker_seconds:,.1f} s summed over worker processes)\n")
    print("| Layer | Seconds | ms per user | Share |")
    print("|-------|--------:|------------:|------:|")
    for layer, seconds in layers.items():
        print(f"| {layer} | {seconds:,.2f} | {seconds / users * 1000:.3f} | {seconds / worker_seconds:.1%} |")
    print(f"\nTop {len(functions)} Python functions by own time\n")
    print("| Function | Calls | Own s | Cumulative s |")
    print("|----------|------:|------:|-------------:|")
    for f in functions:
        print(f"| `{f.function}` | {f.calls:,} | {f.own_seconds:,.3f} | {f.total_seconds:,.3f} |")

def main() -> None:
    load_dotenv(ROOT / ".env")
    settings = Settings.from_env()
    args = parse_args(settings)
    if urlparse(settings.database_url).hostname not in LOCAL_HOSTS and not args.allow_remote:
        sys.exit("DATABASE_URL is not a local server; add --allow-remote to profile it anyway.")

    db = Database.from_settings(replace(settings, db_pool_size=args.workers))
    try:
        server = server_label(db, settings.database_url)
        locales = args.locales or [loc.code for loc in StoredProcedureFaker(db).locales()]
        print(f"Profiling {server} with {args.workers} worker(s), {args.chunk:,} users per call")
        for locale in locales:
            print(f"\n## {locale}")
            if args.primitive_calls:
                print_primitives(profile_primitives(db, locale, args.primitive_calls))
            if args.sql_users:
                plan = BenchmarkPlan(locale, args.sql_users, args.seed, args.chunk, args.workers, args.about_sentences)
                steps = profile_steps(db, plan, lambda done, total, elapsed: print_progress(
                    f"{locale} steps", done, total, elapsed))
                print()
                print_steps(steps)
            if args.users:
                plan = BenchmarkPlan(locale, args.users, args.seed, args.chunk, args.workers, args.about_sentences,
                                     fetch=True)
                stats, wall = profile_python(settings, plan, lambda done, total, elapsed: print_progress(
                    f"{locale} end to end", done, total, elapsed))
                print()
                print_python(args.users, wall, layer_seconds(stats), top_functions(stats, args.top))
    finally:
        db.close()

if __name__ == "__main__":
    main()
