import streamlit as st

from fakerdb.models import Locale

from . import state

def keep_known_locale(locales: list[Locale]) -> None:
    codes = [loc.code for loc in locales]
    if st.session_state.get(state.LOCALE_KEY) not in codes:
        st.session_state[state.LOCALE_KEY] = codes[0]
        state.reset_batch(st.session_state)

def sidebar(locales: list[Locale], default_seed: int, max_seed: int) -> state.Selection:
    state.init_state(st.session_state, locales[0].code, default_seed)
    keep_known_locale(locales)
    names = {loc.code: loc.name for loc in locales}
    session = st.session_state

    with st.sidebar:
        st.header("Generator")
        st.selectbox("Locale", list(names), format_func=names.get, key=state.LOCALE_KEY,
                     on_change=state.reset_batch, args=(session,))
        st.number_input("Seed", min_value=0, max_value=max_seed, step=1, key=state.SEED_KEY,
                        on_change=state.reset_batch, args=(session,))
        st.button("Random seed", icon=":material/casino:", on_click=state.randomize_seed,
                  args=(session, max_seed), width="stretch")
        st.number_input("Batch", min_value=state.FIRST_BATCH_NO, step=1, key=state.BATCH_KEY,
                        help="Jump to any batch: the same locale, seed and batch always give the same people.")
        st.caption("Data is generated by MySQL stored procedures (`faker_generate_users`, `faker_generate_text`).")
    return state.current(session)
