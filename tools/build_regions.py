"""Writes sql/locales/<locale>/05_geo.sql (country border polygons) from Natural Earth admin-0 countries.

python tools/build_regions.py ne_50m_admin_0_countries.geojson
Source: https://github.com/nvkelso/natural-earth-vector (v5.1.2, geojson/), public domain.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT_NAME = "05_geo.sql"
COORDINATE_DECIMALS = 5  
POINTS_PER_LINE = 8
COUNTRY_FIELD = "ADMIN"


COUNTRIES = {
    "de_DE": ("Germany", {"Germany": None}),
    "en_US": ("United States of America", {
        "Contiguous United States": (24.0, 50.0, -125.0, -66.0),
        "Alaska": (51.0, 72.0, -180.0, -129.0),
        "Alaska, Aleutian Islands west of 180": (51.0, 54.0, 172.0, 180.0),
        "Hawaii": (18.5, 22.5, -161.0, -154.5),
    }),
}

def parts_of(geometry: dict) -> list:
    return geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]

def center(part: list) -> tuple[float, float]:
    lons = [lon for lon, _ in part[0]]
    lats = [lat for _, lat in part[0]]
    return (min(lats) + max(lats)) / 2, (min(lons) + max(lons)) / 2

def region_of(part: list, regions: dict) -> str | None:
    lat, lon = center(part)
    for name, box in regions.items():
        if box is None or (box[0] <= lat <= box[1] and box[2] <= lon <= box[3]):
            return name
    return None

def ring_wkt(ring: list) -> str:
    points = [f"{lon:.{COORDINATE_DECIMALS}f} {lat:.{COORDINATE_DECIMALS}f}" for lon, lat in ring]
    lines = [", ".join(points[i:i + POINTS_PER_LINE]) for i in range(0, len(points), POINTS_PER_LINE)]
    return "(" + ",\n".join(lines) + ")"

def multipolygon_wkt(parts: list) -> str:
    return "MULTIPOLYGON(" + ",\n".join("(" + ", ".join(ring_wkt(r) for r in part) + ")" for part in parts) + ")"

def region_sql(locale: str, name: str, parts: list) -> str:
    return f"CALL faker_add_geo_region('{locale}', '{name}', '{multipolygon_wkt(parts)}');\n"

def build(geojson: Path, out_dir: Path, source_label: str) -> None:
    features = {f["properties"][COUNTRY_FIELD]: f for f in json.loads(geojson.read_text(encoding="utf-8"))["features"]}
    for locale, (country, regions) in COUNTRIES.items():
        grouped: dict[str, list] = {name: [] for name in regions}
        for part in parts_of(features[country]["geometry"]):
            name = region_of(part, regions)
            if name is None:
                print(f"{locale}: skipped a part of {country} centred at {center(part)}")
                continue
            grouped[name].append(part)
        body = "".join(region_sql(locale, name, parts) for name, parts in grouped.items() if parts)
        header = (f"-- {country}: border polygons for coordinates ({source_label}, public domain).\n"
                  f"-- Generated by tools/build_regions.py; do not edit by hand.\nSET NAMES utf8mb4;\n")
        target = out_dir / locale / OUTPUT_NAME
        target.write_text(header + body, encoding="utf-8")
        print(f"{target}: " + ", ".join(f"{n} ({len(p)} parts)" for n, p in grouped.items()))

def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("geojson", type=Path, help="ne_50m_admin_0_countries.geojson (or the 10m file)")
    parser.add_argument("--out", type=Path, default=ROOT / "sql" / "locales")
    parser.add_argument("--source", default="Natural Earth admin-0 countries v5.1.2")
    args = parser.parse_args()
    build(args.geojson, args.out, f"{args.source}, {args.geojson.name}")

if __name__ == "__main__":
    main()
